suppressPackageStartupMessages(library(sf))
for(name in c('arcgis','source_classification','barrier_stream_identity','stream_edge_identity',
 'stream_reference','network','phase_barrier_cuts','upstream_basins','nldi_delineation','pilchuck_creek_review'))
 source(file.path('R',paste0(name,'.R')))
directory<-'spatial_data/lake_cavanaugh_review'
old<-readRDS('spatial_data/stillaguamish_review/pilchuck_creek.rds')
original<-pilchuck_source_polygon(old$masks$source_split_basin_cache_file,st_crs(old$masks),'drainageBasin')
lake_basin<-pilchuck_source_polygon('spatial_data/stillaguamish_review/pilchuck_sources/foreign_24275741_whole_basin.json',st_crs(old$masks))
lake<-pilchuck_source_polygon('spatial_data/stillaguamish_review/lake_cavanaugh_audit/nhd_waterbody_24277115.json',st_crs(old$masks))
combined<-st_union(original,lake_basin)
extension<-suppressWarnings(st_difference(combined,original))
remaining<-st_read('outputs/phase3_tidal_barriers/North_Puget_Sound_Steelhead_phase3.gpkg',layer='phase3_remaining',quiet=TRUE)
edges<-st_read('outputs/review_swifd_connections/North_Puget_Sound_Steelhead.gpkg',layer='stream_matching_edges',quiet=TRUE)
raw<-readRDS('spatial_data/north_puget_swifd_bridges.rds')$bridges$network
named<-load_stream_identity_reference()
added<-upstream_line_parts(suppressWarnings(st_intersection(remaining,extension)))
added$length_m<-as.numeric(st_length(added))
mid<-st_line_sample(st_geometry(added),sample=.5)
near<-st_nearest_feature(mid,named)
added$reference_name<-named$reference_stream_name[near]
added$reference_llid<-as.character(named$LLID[near])
added$reference_distance_m<-as.numeric(st_distance(mid,named[near,],by_element=TRUE))
cat('AREAS original/lake_basin/union/extension/lake km2:',as.numeric(st_area(c(original,lake_basin,combined,extension,lake)))/1e6,'\n')
print(st_drop_geometry(added)[,intersect(c('source_class','source_id','graph_edge_id','length_m','reference_name','reference_llid','reference_distance_m'),names(added))])
cat('Added retained total m:',sum(added$length_m),'\n')
new_raw<-upstream_line_parts(suppressWarnings(st_intersection(raw,extension)))
cat('All raw classes in extension:\n');print(aggregate(as.numeric(st_length(new_raw)),list(source_class=new_raw$source_class),sum))
deer<-named[named$reference_stream_name=='Deer Creek',]
cat('Deer reference total/intersect union m:',sum(as.numeric(st_length(deer))),sum(as.numeric(st_length(upstream_line_parts(suppressWarnings(st_intersection(deer,combined)))))),'\n')
extent<-st_bbox(st_buffer(lake_basin,2000))
png(file.path(directory,'lake_cavanaugh_extension_audit.png'),width=1800,height=1200)
plot(combined,col='#d7efdd',border='#408040',xlim=extent[c('xmin','xmax')],ylim=extent[c('ymin','ymax')],main='Lake Cavanaugh: actual waterbody, original634 basin, omitted tributary catchment')
plot(extension,col='#ffe4be',border='#a26b00',add=TRUE)
plot(lake,col='#88c8ec',border='#1177aa',add=TRUE)
plot(st_geometry(named),col='#a6a6a6',lwd=.8,add=TRUE)
plot(st_geometry(deer),col='#b041b9',lwd=2,add=TRUE)
plot(st_geometry(added),col='red',lwd=4,add=TRUE)
plot(st_geometry(old$barriers),pch=21,bg='orange',cex=1.4,add=TRUE)
dev.off()
saveRDS(list(original=original,lake_basin=lake_basin,lake=lake,combined=combined,extension=extension,added=added,all_raw_added=new_raw,named=named,edges=edges),file.path(directory,'extension_audit.rds'))
