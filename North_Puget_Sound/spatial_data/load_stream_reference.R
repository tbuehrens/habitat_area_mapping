source("R/arcgis.R")
source("R/stream_reference.R")
library(sf)
reference <- load_stream_identity_reference()
cat("REFERENCE FEATURES", nrow(reference), "UNIQUE LLIDs", length(unique(reference$LLID)), "\n")
cat("UNNAMED REFERENCES", sum(is.na(reference$reference_stream_name)), "\n")
point <- st_sfc(st_point(c(-121.2082, 48.6978)), crs = 4326)
point <- st_transform(point, 26910)
nearest <- st_nearest_feature(point, reference)
print(st_drop_geometry(reference[nearest, c("LLID", "LLID_STREAMNAME", "GNIS_STREAMNAME", "GNIS_Name")]))
cat("GORGE NEAREST REFERENCE DISTANCE M", as.numeric(st_distance(point, reference[nearest, ], by_element = TRUE)), "\n")
model <- readRDS("spatial_data/north_puget_steelhead.rds")
cat("MODEL MAX_UniqueCHID unique count", length(unique(model$MAX_UniqueCHID)), "\n")
print(head(unique(model$MAX_UniqueCHID), 10))
swifd <- st_transform(readRDS("spatial_data/north_puget_swifd_steelhead.rds"), 26910)
near_swifd <- st_nearest_feature(point, swifd)
cat("GORGE ELIGIBLE SWIFD REFERENCE DISTANCE M", as.numeric(st_distance(point, swifd[near_swifd, ], by_element=TRUE)), "\n")
print(st_drop_geometry(swifd[near_swifd, c("LLID", "LLID_STRM_NAME")]))
